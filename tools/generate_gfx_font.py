#!/usr/bin/env python3
from PIL import Image, ImageDraw, ImageFont
import requests
import os

FONT_URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/montserrat/Montserrat[wght].ttf'
OUT_DIR = 'lib/fonts'
CHARS = [chr(i) for i in range(0x20, 0x7f)]
SIZES = [48, 24]

os.makedirs(OUT_DIR, exist_ok=True)

r = requests.get(FONT_URL)
if r.status_code != 200:
    raise SystemExit('Failed to download font')

ttf_path = os.path.join(OUT_DIR, 'Montserrat-Regular.ttf')
with open(ttf_path, 'wb') as f:
    f.write(r.content)

print('Downloaded TTF to', ttf_path)

# helper to pack bit rows MSB->LSB

def pack_bits(row_pixels):
    # row_pixels: list of 0/1, left-to-right. pack MSB first
    b = []
    val = 0
    cnt = 0
    for pix in row_pixels:
        val = (val << 1) | (1 if pix else 0)
        cnt += 1
        if cnt == 8:
            b.append(val)
            val = 0
            cnt = 0
    if cnt > 0:
        val = val << (8 - cnt)
        b.append(val)
    return b

for size in SIZES:
    font = ImageFont.truetype(ttf_path, size=size)
    ascent, descent = font.getmetrics()
    print('Generating size', size, 'ascent', ascent, 'descent', descent)

    bitmaps = []
    glyphs = []
    offset = 0
    max_height = 0
    for ch in CHARS:
        # render on large image and crop
        image = Image.new('L', (size*4, size*4), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0,0), ch, font=font, fill=255)
        bbox = image.getbbox()
        if not bbox:
            # empty glyph (space) - compute xAdvance by measuring text bbox
            try:
                tb = draw.textbbox((0,0), ch, font=font)
                xAdvance = max(1, tb[2] - tb[0])
            except Exception:
                # fallback
                xAdvance = max(1, int(font.getmask(ch).size[0]))
            w = xAdvance
            h = 1
            glyphs.append((offset, w, h, xAdvance, 0, 0))
            # no bitmap bytes
            continue
        left, upper, right, lower = bbox
        w = right - left
        h = lower - upper
        if h > max_height:
            max_height = h
        # crop
        gm = image.crop((left, upper, right, lower))
        # convert to 1-bit by threshold
        bw = gm.point(lambda p: 1 if p > 127 else 0, '1')
        rows = []
        for yy in range(h):
            row = [1 if bw.getpixel((xx, yy)) else 0 for xx in range(w)]
            rows.append(row)
        # pack rows
        bdata = []
        for row in rows:
            bdata.extend(pack_bits(row))
        bitmaps.extend(bdata)
        try:
            tb = draw.textbbox((0,0), ch, font=font)
            xAdvance = max(1, tb[2] - tb[0])
        except Exception:
            xAdvance = max(1, int(font.getmask(ch).size[0]))
        xOffset = 0
        yOffset = ascent - lower
        glyphs.append((offset, w, h, xAdvance, xOffset, yOffset))
        offset += len(bdata)

    # create header
    name = f'Montserrat{size}pt7b'
    hpath = os.path.join(OUT_DIR, f'{name}.h')
    with open(hpath, 'w', encoding='utf8') as hf:
        hf.write('// Generated by tools/generate_gfx_font.py - subset ASCII 0x20..0x7E\n')
        hf.write(f'#ifndef {name.upper()}_H\n')
        hf.write(f'#define {name.upper()}_H\n\n')
        hf.write('#include <gfxfont.h>\n\n')
        hf.write(f'const uint8_t {name}Bitmaps[] PROGMEM = {{\n')
        # write bytes
        for i, val in enumerate(bitmaps):
            if i % 12 == 0:
                hf.write('  ')
            hf.write(f'0x{val:02X}, ')
            if (i+1) % 12 == 0:
                hf.write('\n')
        hf.write('\n};\n\n')
        hf.write(f'const GFXglyph {name}Glyphs[] PROGMEM = {{\n')
        for i,ch in enumerate(CHARS):
            g = glyphs[i]
            hf.write(f'  {{ {g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]} }}, // 0x{ord(ch):02X} \'{ch}\'\n')
        hf.write('};\n\n')
        hf.write(f'const GFXfont {name} PROGMEM = {{ (uint8_t  *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x20, 0x7E, {max_height} }};\n\n')
        hf.write(f'#endif // {name.upper()}_H\n')
    print('Wrote', hpath)

print('Done')
